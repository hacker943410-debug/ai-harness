import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {copyTree,treeFiles} from '../lib/io.mjs';
import {metadata} from '../lib/skills.mjs';
import {readSkill} from '../lib/skills.mjs';
import {install} from '../lib/install.mjs';
import {rootFor} from '../lib/io.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
test('company Word skill is discoverable and shipped in both Core and common payload',t=>{
 const folder=path.join(root,'core/skills/jh-company-word');
 const skill=metadata(path.join(folder,'SKILL.md'));
 assert.equal(skill.name,'jh-company-word');
 assert.match(skill.description,/Word/);
 const catalog=JSON.parse(fs.readFileSync(path.join(root,'catalogs/skill-catalog.json'),'utf8'));
 const row=catalog.entries.filter(x=>x.id===skill.name);
 assert.equal(row.length,1);
 assert.equal(row[0].bundled_path,'core/skills/jh-company-word');
 const manifest=JSON.parse(fs.readFileSync(path.join(root,'harness/manifest.yaml'),'utf8'));
 const temporary=fs.mkdtempSync(path.join(os.tmpdir(),'cw-skill-distribution-'));
 t.after(()=>fs.rmSync(temporary,{recursive:true,force:true}));
 const distribution=path.join(temporary,'skill');copyTree(folder,distribution);
 for(const item of treeFiles(distribution))assert.ok(manifest.payload_files.includes('core/skills/jh-company-word/'+item.path));
 assert.ok(!treeFiles(distribution).some(x=>/\.(docx|pdf|png)$/i.test(x.path)),'private company assets must not ship');
});
test('runtime copy retains Python source while omitting generated bytecode',t=>{
 const base=fs.mkdtempSync(path.join(os.tmpdir(),'cw-packaging-'));
 t.after(()=>fs.rmSync(base,{recursive:true,force:true}));
 const source=path.join(base,'source'),target=path.join(base,'runtime');
 fs.mkdirSync(path.join(source,'__pycache__'),{recursive:true});
 fs.writeFileSync(path.join(source,'helper.py'),'# source\n');
 fs.writeFileSync(path.join(source,'__pycache__/helper.pyc'),'generated');
 fs.writeFileSync(path.join(source,'stray.pyc'),'generated');
 copyTree(source,target);
 assert.deepEqual(treeFiles(target).map(x=>x.path),['helper.py']);
});

function installedFixture(t){
 const base=fs.mkdtempSync(path.join(os.tmpdir(),'cw-installed-discovery-'));
 t.after(()=>fs.rmSync(base,{recursive:true,force:true}));
 const h=path.join(base,'home'),project=path.join(base,'project'),bin=path.join(base,'bin');
 fs.mkdirSync(h);fs.mkdirSync(project);fs.mkdirSync(path.join(bin,'node_modules/@openai/codex/bin'),{recursive:true});
 fs.writeFileSync(path.join(bin,'node_modules/@openai/codex/bin/codex.js'),'console.log("codex-cli 0.0.0-synthetic");\n');
 const before=process.env.PATH;process.env.PATH=bin;
 try{install(h);}finally{if(before===undefined)delete process.env.PATH;else process.env.PATH=before;}
 return{h,project,builtin:path.join(rootFor(h),'runtime/core/skills/jh-company-word')};
}

test('identical native copies resolve to the installed builtin without executing helper scripts',t=>{
 const{h,project,builtin}=installedFixture(t);
 copyTree(builtin,path.join(project,'.agents/skills/jh-company-word'));
 copyTree(builtin,path.join(h,'skills/jh-company-word'));
 const row=readSkill(h,project,'jh-company-word',{includeUser:false});
 assert.equal(row.kind,'BUILTIN');
 assert.equal(row.file,path.join(builtin,'SKILL.md'));
 assert.equal(row.equivalentDiscoveredCopies,2);
 assert.equal(row.queryOnly,true);
});

test('same metadata with changed native helper remains blocked',t=>{
 const{h,project,builtin}=installedFixture(t),native=path.join(project,'.agents/skills/jh-company-word');
 copyTree(builtin,native);
 fs.appendFileSync(path.join(native,'scripts/company_word.py'),'\n# locally changed helper\n');
 assert.throws(()=>readSkill(h,project,'jh-company-word',{includeUser:false}),/DUPLICATE/);
});
