import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {copyTree,treeFiles} from '../lib/io.mjs';
import {metadata} from '../lib/skills.mjs';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
test('company Word skill is discoverable and shipped in both Core and common payload',t=>{
 const folder=path.join(root,'core/skills/jh-company-word');
 const skill=metadata(path.join(folder,'SKILL.md'));
 assert.equal(skill.name,'jh-company-word');
 assert.match(skill.description,/Word/);
 const catalog=JSON.parse(fs.readFileSync(path.join(root,'catalogs/skill-catalog.json'),'utf8'));
 const row=catalog.entries.filter(x=>x.id===skill.name);
 assert.equal(row.length,1);
 assert.equal(row[0].bundled_path,'core/skills/jh-company-word');
 const manifest=JSON.parse(fs.readFileSync(path.join(root,'harness/manifest.yaml'),'utf8'));
 const temporary=fs.mkdtempSync(path.join(os.tmpdir(),'cw-skill-distribution-'));
 t.after(()=>fs.rmSync(temporary,{recursive:true,force:true}));
 const distribution=path.join(temporary,'skill');copyTree(folder,distribution);
 for(const item of treeFiles(distribution))assert.ok(manifest.payload_files.includes('core/skills/jh-company-word/'+item.path));
 assert.ok(!treeFiles(distribution).some(x=>/\.(docx|pdf|png)$/i.test(x.path)),'private company assets must not ship');
});
test('runtime copy retains Python source while omitting generated bytecode',t=>{
 const base=fs.mkdtempSync(path.join(os.tmpdir(),'cw-packaging-'));
 t.after(()=>fs.rmSync(base,{recursive:true,force:true}));
 const source=path.join(base,'source'),target=path.join(base,'runtime');
 fs.mkdirSync(path.join(source,'__pycache__'),{recursive:true});
 fs.writeFileSync(path.join(source,'helper.py'),'# source\n');
 fs.writeFileSync(path.join(source,'__pycache__/helper.pyc'),'generated');
 fs.writeFileSync(path.join(source,'stray.pyc'),'generated');
 copyTree(source,target);
 assert.deepEqual(treeFiles(target).map(x=>x.path),['helper.py']);
});
